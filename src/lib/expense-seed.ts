export interface SeedRow {
  category: string;
  item: string;
  /** false = ไม่นับเป็นค่าใช้จ่าย (หักจากรายได้) */
  counted: boolean;
  note: string;
}

const ADJUSTABLE_NOTE = "ตั้งต้น — ปรับชื่อรายการได้ในแท็บนี้";

/** กลุ่ม → แถว seed (1 แถวต่อ 1 ชื่อรายการ ตามลำดับหมวดที่ตกลงกัน) */
const group = (
  category: string,
  items: readonly string[],
  opts?: { counted?: boolean; note?: string },
): SeedRow[] =>
  items.map((item) => ({
    category,
    item,
    counted: opts?.counted ?? true,
    note: opts?.note ?? "",
  }));

